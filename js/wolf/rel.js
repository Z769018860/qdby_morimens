// 取关系：0 = 没关系，正数 = 亲近，负数 = 有仇
export function relOf(a, b) {
  if (!a || !b || a === b) return 0;
  const r = REL[a];
  if (!r) return 0;
  if (r.like && r.like.indexOf(b) >= 0) return 1;
  if (r.war && r.war.indexOf(b) >= 0) return -1;
  return 0;
}
