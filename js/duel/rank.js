// 这套对手打你这套的胜率（百分数）。表里没有的一律当五五开，别让新牌组炸掉选牌。
//
// 第三个数 w 是「替身权重」：玩家自己组的牌没有实测对位（COUNTER 只有预组的行），
// 传进来的是它最像的那两三套预组 { d5: 1, d12: 0.6 }，按权重把几行混起来。
// 不传就退回「表里有就用、没有给 50」——自组牌一律 50 的话，对手等于随机挑一套，
// 高段位「专挑死克你的」这条对自组玩家直接失效（这也是「自组速攻能速通」的一半原因）。
function wrOf(foeId, myId, w) {
  const row = COUNTER[foeId];
  if (!row) return 50;
  if (w) {
    let sum = 0, tot = 0;
    for (const k of Object.keys(w)) {
      const v = row[k];
      if (typeof v === 'number') { sum += v * w[k]; tot += w[k]; }
    }
    if (tot > 0) return sum / tot;
  }
  const v = row[myId];
  return typeof v === 'number' ? v : 50;
}

export function foeWinRate(foeId, myId, w) { return wrOf(foeId, myId, w); }

// 自组卡组 → 「最像哪几套预组」的权重，喂给上面 wrOf 的 w。
// cards 是 [[卡id, 张数], …]，presets 是那批预组（引擎侧传 PRESETS，页面传 PICK_DECKS）。
// 权重按最像那套归一化（1 / 0.6 / 0.3），只取前三套——玩家自组的牌本来就是一两个流派的拼盘，
// 铺太开反而把克制关系抹平。放在 rank.js 是为了让脚本能走和线上同一条路径。
export function proxyWeights(cards, presets) {
  const mine = new Set((cards || []).map((c) => (Array.isArray(c) ? c[0] : c)));
  const sims = (presets || []).map((d) => {
    let hit = 0;
    for (const c of d.cards) if (mine.has(Array.isArray(c) ? c[0] : c)) hit++;
    // 分母用两边较小的那张数：自组 40 张、预组 45 张，直接除会系统性偏低
    return { id: d.id, s: hit / Math.max(1, Math.min(mine.size, d.cards.length)) };
  }).filter((x) => x.s > 0).sort((a, b) => b.s - a.s).slice(0, 3);
  if (!sims.length) return null;
  const top = sims[0].s;
  const out = {};
  for (const x of sims) out[x.id] = x.s / top;
  return out;
}

// 人机的候选池：混合卡组（x01~x12）从 pool>=0.5 起才进池。
//
// 为什么不一上来就给：低段位的设定是「榜单上的玩家拿自己那套预组」，一个心不在焉的人
// 不会自己拆两套牌重组；等到「挑牌」这一档开始动脑子（Lv7 左右），对手才逐渐变成
// 「自己也混牌的人」。这也顺带控住了混牌的出现率——34 套里 12 套是混牌，全放进去
// 低段位会有三成的对局变成混牌，那就不像「对手在按自己的路子打」了。
export const MIX_FROM = 0.5;
export function foeIds(ids, pool) {
  const p = Number(pool) || 0;
  return p >= MIX_FROM ? ids.slice() : ids.filter((id) => !/^x\d/.test(id));
}

// 对手牌组怎么挑：**分位段**，不是加权抽。
//
// 把除自己那套以外的预组按「它打你这套的胜率」从低到高排好，取一个固定宽度的窗口，
// 窗口中心随 pool 从偏弱（20 分位）挪到偏强（92 分位），窗口内均匀抽。
// 这么做的三个理由：
//   1. 期望难度可算：窗口中心就是这一档「大约让对手多强」，不用猜权重；
//   2. 同档方差小：加权抽会冷不丁甩给你 89% 胜率的那套（旧版 d22 玩家在顶档只有 5% 胜率）；
//   3. 玩家看得懂：主页能把「这一档可能坐下来的牌组」原样列出来（foeBand 返回的就是那几套）。
//
// FOE_CAP 是默认的「死克你的牌组不进池」保险。它挡掉的正是「换一套牌就得跪」的对局，
// 代价是顶档的天花板降到 47% 左右——宁可难，不要没法打。
// 但 pool 到 1、sloppy 到 0 之后这两颗螺丝就拧不动了，所以唤醒王之上那四档改成按档位
// 传 cap（放开保险）/ band（收窄窗口）：候选越窄越贴着最克的那一端，cap 越高越允许死克你的进来。
export const FOE_CAP = 72;
const FOE_BAND = 44;      // 窗口宽度（百分位）
const FOE_LO = 0.20;      // pool=0 时窗口中心（百分位）
const FOE_HI = 0.92;      // pool=1 时窗口中心

// 这一档对手可能用的牌组（按胜率升序）。ids 传全部预组 id。
// opt 可覆盖默认的 cap / band（见 AI_LV 后四档）；opt.my 是自组卡组的替身权重
// （{ d5: 1, d12: 0.6 }），传了它 myId 就只是个去重用的标识。不传就是老行为。
export function foeBand(pool, myId, ids, opt) {
  const o = opt || {};
  const cap = o.cap != null ? Number(o.cap) : FOE_CAP;
  const width = o.band != null ? Math.max(4, Number(o.band)) : FOE_BAND;
  const list = (ids || []).filter((id) => id !== myId)
    .map((id) => ({ id, wr: wrOf(id, myId, o.my) }))
    .filter((x) => x.wr <= cap)
    .sort((a, b) => a.wr - b.wr);
  if (!list.length) return [];
  const p = Math.max(0, Math.min(1, Number(pool) || 0));
  const mid = FOE_LO + p * (FOE_HI - FOE_LO);
  const lo = Math.max(0, mid - width / 200);
  const hi = Math.min(1, mid + width / 200);
  let seg = list.slice(Math.floor(lo * list.length), Math.max(1, Math.ceil(hi * list.length)));
  if (!seg.length) seg = [list[list.length - 1]];
  return seg.map((x) => x.id);
}

// pool → 人话（窗口中心落在第几分位）。放在这里而不是 view：改窗口参数时文案要一起变。
// band 传了就在后面补一句窗口有多窄——后四档的差别全在这个宽度上，光说「专挑死克你的」
// 分不出「在 10 套里挑」和「在 2 套里挑」。
export function poolLabel(pool, band) {
  const p = Math.max(0, Math.min(1, Number(pool) || 0));
  const mid = (FOE_LO + p * (FOE_HI - FOE_LO)) * 100;
  let s;
  if (mid < 25) s = '只挑打不过你的';
  else if (mid < 35) s = '挑偏弱的';
  else if (mid < 45) s = '挑略弱的';
  else if (mid < 55) s = '挑势均力敌的';
  else if (mid < 65) s = '挑偏克你的';
  else if (mid < 75) s = '挑很克你的';
  else if (mid < 85) s = '挑最克你的';
  else s = '专挑死克你的';
  if (band != null && Number(band) < FOE_BAND) s += `（${Math.round(Number(band))} 分位窄窗）`;
  return s;
}

// rnd 默认 Math.random，模拟脚本可以塞一个可复现的流。opt 见 foeBand（含 opt.my）。
export function foePick(pool, myId, ids, rnd, opt) {
  const seg = foeBand(pool, myId, ids, opt);
  if (!seg.length) {
    const other = (ids || []).filter((id) => id !== myId);
    return other.length ? other[0] : null;
  }
  return seg[Math.floor((rnd || Math.random)() * seg.length)];
}

// 档位是**连续刻度**：1 ~ 14 之间可以取小数，参数在相邻两档之间线性插值。
//
// 为什么不是整数档：段位只有十几格，整数档无论如何都会出现「升了一段还是同一档」
// （旧版「认真」从第 5 段起就一直是 Lv8，后五档完全一样）。改成连续刻度后，
// 每升一段都真的强一点，档名只是给这条刻度挂的锚点。
//
// cap / band / lp 只从 Lv11 起才有值。低档位插值时如果一头是 undefined 就取另一头，
// 两头都没有就返回 undefined（交给 foeBand 用自己的默认值）。
function mix(a, b, f, key) {
  const va = a[key], vb = b[key];
  if (va == null && vb == null) return undefined;
  if (va == null) return vb;
  if (vb == null) return va;
  return va + (vb - va) * f;
}

export function lvAt(x) {
  const t = Math.max(1, Math.min(AI_LV.length, Number(x) || 1));
  const i = Math.min(AI_LV.length - 1, Math.floor(t - 1));
  const j = Math.min(AI_LV.length - 1, i + 1);
  const f = t - 1 - i;
  const a = AI_LV[i];
  const b = AI_LV[j];
  return {
    lv: Math.round(t), x: t, n: f < 0.5 ? a.n : b.n,
    sloppy: a.sloppy + (b.sloppy - a.sloppy) * f,
    pool: a.pool + (b.pool - a.pool) * f,
    cap: mix(a, b, f, 'cap'),
    band: mix(a, b, f, 'band'),
    lp: mix(a, b, f, 'lp'),
    max: AI_LV.length,
  };
}

// 三条难度线各占一段刻度，都从「能赢」走到「要拼」：
//   · 轻松 1 → 6.5 ：顶段也就 60% 出头，选轻松的人不该被逼着认真；
//   · 普通 2 → 10  ：顶段 ≈ 45%；
//   · 认真 4 → 14  ：顶段「弥萨格校猫」≈ 35%。
// 区间重叠是故意的——玩家可以在普通的顶段遇到「认真」开局那种强度，但名字和曲线还是分开的。
//
// 段位从 9 段扩到 13 段之后，这个映射要一起重算：分母是 TIERS.length - 1，
// 段位一多，同样一个 lo→hi 的跨度被摊得更细，所以 hi 要跟着抬，否则新加的四段会「原地不动」。
const RANGE = { easy: [1, 6.5], normal: [2, 10], hard: [4, 14] };

export function aiFor(diff, tierIdx) {
  const key = RANGE[diff] ? diff : 'normal';
  const [lo, hi] = RANGE[key];
  const t = Math.max(0, Math.min(TIERS.length - 1, Number(tierIdx) || 0));
  const x = lo + (hi - lo) * (t / (TIERS.length - 1));
  return lvAt(x);
}

