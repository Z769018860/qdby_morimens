def patch_packs(add_text, anchor, what):
    path = os.path.join(ROOT, 'data/duel-packs.json')
    raw = open(path, encoding='utf-8').read()
    if anchor not in raw:
        raise SystemExit('找不到 %s 的插入锚点，先看文件结构有没有变' % what)
    idx = raw.rindex(anchor)
    head, tail = raw[:idx], raw[idx:]
    # 新条目本身可能以「},\n」结尾（方便以后继续往后追加），插到数组末尾时那个逗号就多余了
    body = add_text.strip().rstrip(',')
    out = head.rstrip('\n').rstrip() + ',' + '\n' + body + tail
    open(path, 'w', encoding='utf-8', newline='').write(out)


def main():
    cards = read_json('data/duel-cards.json')
    have = {c['id'] for k in ('monsters', 'spells', 'traps', 'extras') for c in cards[k]}
    names = {c['n'] for k in ('monsters', 'spells', 'traps', 'extras') for c in cards[k]}

    added = []

    def push(bucket, items):
        for c in items:
            if c['id'] in have:
                continue
            if c['n'] in names:
                print('跳过重名：', c['n'])
                continue
            cards[bucket].append(c)
            have.add(c['id'])
            names.add(c['n'])
            added.append(c['id'])

    push('monsters', BP08_MONS + BP09_MONS + BP10_MONS)
    push('spells', BP07_EQUIP + BP07_MORE)
    push('traps', BP07_TRAPS)
    push('extras', BP08_EXTRAS)

    write_json('data/duel-cards.json', cards)
    print('新增 %d 张卡' % len(added))
    allc = {c['id']: c for k in ('monsters', 'spells', 'traps', 'extras') for c in cards[k]}
    print('卡表合计 %d 张（怪兽 %d / 魔法 %d / 陷阱 %d / 觉醒体 %d）' % (
        len(allc), len(cards['monsters']), len(cards['spells']),
        len(cards['traps']), len(cards['extras'])))

    packs = read_json('data/duel-packs.json')
    if not any(p['id'] == 'bp07' for p in packs['packs']):
        patch_packs(PACKS_TEXT, PACK_ANCHOR, '卡包')
        print('已插入 bp07~bp10')
    if not any(d['id'] == 'd12' for d in packs['decks']):
        patch_packs(DECKS_TEXT, DECK_ANCHOR, '预组')
        print('已插入 d12~d18')

    # 自检：预组张数、引用的卡是否存在、装备对象是否是真实存在的怪兽
    chk = read_json('data/duel-packs.json')
    bad = []
    mon_names = {c['n'] for c in cards['monsters']}
    for s in cards['spells']:
        if s.get('for') and s['for'] not in mon_names:
            bad.append('装备 %s 的 for「%s」不是怪兽卡' % (s['id'], s['for']))
    for d in chk['decks']:
        n = sum(k for _, k in d['cards'])
        if n != 30:
            bad.append('预组 %s 是 %d 张' % (d['id'], n))
        for cid, _ in d['cards']:
            if cid not in allc:
                bad.append('预组 %s 引用了不存在的 %s' % (d['id'], cid))
        for cid in d['extra']:
            if cid not in allc:
                bad.append('预组 %s 额外卡组引用了 %s' % (d['id'], cid))
    for p in chk['packs']:
        for cid in p['cards']:
            if cid not in allc:
                bad.append('卡包 %s 引用了不存在的 %s' % (p['id'], cid))
    print('卡包', len(chk['packs']), '预组', len(chk['decks']))
    print('自检问题：' + ('、'.join(bad) if bad else '无'))
    return 1 if bad else 0


