"""扩充《唤醒王：决斗链接》的卡池：bp07 造物与命轮 / bp08 融灾首领 / bp09 灯与手术刀 / bp10 兽群与灰烬。

为什么是一个脚本而不是手改 JSON：卡表两百多张牌，手改一次错一处，
`text` 和 `fx` 一旦对不上，玩家看到的效果和实际结算就成了两回事。
这里把「效果 + 文案」写成一行一条，脚本负责写进 data/duel-cards.json；
重复执行不会重复插入（按 id 与名字判重）。

卡包与预组是手写的紧凑格式（一行一条），JSON 重排会把 6 行改动变成上千行 diff，
所以那部分走字符串插入，锚点写在 PACK_ANCHOR / DECK_ANCHOR。
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_json(rel):
    with open(os.path.join(ROOT, rel), encoding='utf-8') as f:
        return json.load(f)


def write_json(rel, data):
    with open(os.path.join(ROOT, rel), 'w', encoding='utf-8', newline='') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write('\n')


# ------------------------------------------------------------------ 造卡的小助手
def mon(i, n, r, rar, lv, atk, dfn, role, fx, text):
    return {'id': i, 'n': n, 'r': r, 'rar': rar, 'lv': lv, 'atk': atk, 'def': dfn,
            'role': role, 'fx': fx, 'text': text}


def spell(i, n, r, rar, t, fx, text, owner=None):
    c = {'id': i, 'n': n, 'r': r, 'rar': rar, 't': t, 'fx': fx, 'text': text}
    if owner:
        c['for'] = owner          # 装备卡：优先贴在谁身上
    return c


def trap(i, n, r, rar, t, fx, text):
    return {'id': i, 'n': n, 'r': r, 'rar': rar, 't': t, 'fx': fx, 'text': text}


def extra(i, n, r, rar, atk, dfn, mat, fx, text):
    return {'id': i, 'n': n, 'r': r, 'rar': rar, 'atk': atk, 'def': dfn, 'mat': mat, 'fx': fx, 'text': text}


