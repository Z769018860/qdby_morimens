const tok = (w) => `[${String(VOCAB.indexOf(w) + 1).padStart(2, '0')}]`;
export function enc(plain) {
  const words = [...VOCAB].sort((a, b) => b.length - a.length);
  let out = '', i = 0;
  while (i < plain.length) {
    const w = words.find((x) => plain.startsWith(x, i));
    if (w) { out += tok(w); i += w.length; } else { out += plain[i]; i++; }
  }
  return out;
}

